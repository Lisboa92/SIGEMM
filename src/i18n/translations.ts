/**
 * Helper function to translate status keys
 */
export function getStatusLabel(status: string | undefined | null, lang: Lang = 'pt'): string {
  if (!status) return '';
  const key = `status.${status.toLowerCase()}`;
  return translations[lang][key] ?? translations.pt[key] ?? status.replace('_', ' ');
}

/**
 * Helper function to translate role keys
 */
export function getRoleLabel(role: string | undefined | null, lang: Lang = 'pt'): string {
  if (!role) return '';
  const key = `role.${role.toLowerCase()}`;
  return translations[lang][key] ?? translations.pt[key] ?? role;
}
